"""Generate JSON Schema + TypeScript from Pydantic v2 models. Use --check in CI."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from backend.contracts.v2.models import MODELS, SCHEMA_VERSION  # noqa: E402


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(ts_type(child) for child in schema[union])
    if "allOf" in schema:
        return " & ".join(ts_type(child) for child in schema["allOf"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(ts_type({**schema, "type": item}) for item in kind)
    if kind == "null":
        return "null"
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        if not properties:
            additional = schema.get("additionalProperties", True)
            return f"Record<string, {ts_type(additional) if isinstance(additional, dict) else 'unknown'}>"
        required = set(schema.get("required", []))
        lines = ["{"]
        for name, value in properties.items():
            optional = "" if name in required else "?"
            lines.append(f"  {json.dumps(name)}{optional}: {ts_type(value)};")
        additional = schema.get("additionalProperties", False)
        if additional:
            lines.append(f"  [key: string]: {ts_type(additional) if isinstance(additional, dict) else 'unknown'};")
        return "\n".join([*lines, "}"])
    return "unknown"


def artifacts() -> dict[Path, str]:
    outputs = {}
    schemas = {name: model.model_json_schema(mode="validation") for name, model in sorted(MODELS.items())}
    index = {"schema_version": SCHEMA_VERSION, "source": "backend/contracts/v2/models.py", "models": {}}
    ts = [
        "// GENERATED by python scripts/generate_contracts.py; DO NOT EDIT.",
        "// Source: backend/contracts/v2/models.py. Runtime validation belongs to the server.",
        f"export const SCHEMA_VERSION = {json.dumps(SCHEMA_VERSION)} as const;", "",
    ]
    for name, schema in schemas.items():
        filename = f"{name}.schema.json"
        index["models"][name] = filename
        wire_schema = {"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": f"urn:cqa:contracts:{SCHEMA_VERSION}:{name}", **schema}
        outputs[ROOT / "contracts" / "v2" / filename] = json.dumps(wire_schema, ensure_ascii=False, indent=2) + "\n"
        ts.append(f"export type {name} = {ts_type(schema)};\n")
    outputs[ROOT / "contracts" / "v2" / "index.json"] = json.dumps(index, ensure_ascii=False, indent=2) + "\n"
    outputs[ROOT / "src" / "generated" / "contracts.ts"] = "\n".join(ts)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if committed artifacts differ from the models")
    args = parser.parse_args()
    outputs = artifacts()
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("Stale generated contract artifacts:\n" + "\n".join(stale), file=sys.stderr)
        return 1
    print(f"{'Checked' if args.check else 'Generated'} {len(outputs)} contract artifacts for v{SCHEMA_VERSION}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
